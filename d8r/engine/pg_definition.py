"""Explicit PostgreSQL definition reads. Never part of schema refresh or AI context."""
from __future__ import annotations

from d8r.sql import quote_identifier, relation_parts

from .datasources import (
    DataSource, EngineError, _PG_COLLATION_ACCESS, _PG_COLLATION_PROVIDERS, _PG_RELATION_ACCESS,
    _PG_RELATION_KINDS, _PG_ROUTINE_ACCESS, _PG_SCHEMA_USAGE, _PG_SEQUENCE_ACCESS, _PG_TYPE_ACCESS, _safe_error,
)

_ROUTINE = f"""
SELECT pg_catalog.pg_get_functiondef(p.oid)
FROM pg_catalog.pg_proc p JOIN pg_catalog.pg_namespace n ON n.oid = p.pronamespace
WHERE n.nspname = %s AND p.proname = %s AND p.oid = %s AND p.prokind <> 'a' AND {_PG_ROUTINE_ACCESS}
"""
_INDEX = f"""
SELECT pg_catalog.pg_get_indexdef(ix.oid)
FROM pg_catalog.pg_index i
JOIN pg_catalog.pg_class ix ON ix.oid = i.indexrelid
JOIN pg_catalog.pg_class c ON c.oid = i.indrelid
JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace
WHERE n.nspname = %s AND ix.relname = %s AND {_PG_RELATION_ACCESS}
"""
_RELATION = f"""
FROM pg_catalog.pg_class c JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace
WHERE n.nspname = %s AND c.relname = %s AND c.relkind = %s AND {_PG_RELATION_ACCESS}
"""
_VIEW = "SELECT pg_catalog.pg_get_viewdef(c.oid, true) " + _RELATION
_TABLE = """
SELECT pg_catalog.pg_get_partkeydef(c.oid), pg_catalog.pg_get_expr(c.relpartbound, c.oid),
       ARRAY(SELECT pg_catalog.quote_ident(a.attname) || ' ' || pg_catalog.format_type(a.atttypid, a.atttypmod)
                    || CASE a.attidentity WHEN 'a' THEN ' GENERATED ALWAYS AS IDENTITY'
                                          WHEN 'd' THEN ' GENERATED BY DEFAULT AS IDENTITY' ELSE '' END
                    || CASE WHEN a.attnotnull THEN ' NOT NULL' ELSE '' END
                    || COALESCE(CASE WHEN pg_catalog.to_jsonb(a)->>'attgenerated' IN ('s', 'v')
                                THEN ' GENERATED ALWAYS AS (' || pg_catalog.pg_get_expr(d.adbin, c.oid) || ') '
                                     || CASE pg_catalog.to_jsonb(a)->>'attgenerated' WHEN 's' THEN 'STORED' ELSE 'VIRTUAL' END
                                ELSE ' DEFAULT ' || pg_catalog.pg_get_expr(d.adbin, c.oid) END, '')
             FROM pg_catalog.pg_attribute a LEFT JOIN pg_catalog.pg_attrdef d
               ON d.adrelid = a.attrelid AND d.adnum = a.attnum
             WHERE a.attrelid = c.oid AND a.attnum > 0 AND NOT a.attisdropped ORDER BY a.attnum),
       ARRAY(SELECT 'CONSTRAINT ' || pg_catalog.quote_ident(k.conname) || ' ' || pg_catalog.pg_get_constraintdef(k.oid)
             FROM pg_catalog.pg_constraint k WHERE k.conrelid = c.oid AND k.contype <> 'n' ORDER BY k.conname)
""" + _RELATION
_SEQUENCE = f"""
SELECT pg_catalog.format_type(s.seqtypid, NULL), s.seqstart, s.seqincrement,
       s.seqmin, s.seqmax, s.seqcache, s.seqcycle
FROM pg_catalog.pg_sequence s JOIN pg_catalog.pg_class c ON c.oid = s.seqrelid
JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace
WHERE n.nspname = %s AND c.relname = %s AND {_PG_SEQUENCE_ACCESS}
"""
_EXTENSION = f"""
SELECT e.extversion, n.nspname, e.extrelocatable
FROM pg_catalog.pg_extension e JOIN pg_catalog.pg_namespace n ON n.oid = e.extnamespace
WHERE e.extname = %s AND {_PG_SCHEMA_USAGE}
"""
_COLLATION = f"""
SELECT c.collprovider, COALESCE(pg_catalog.to_jsonb(c)->>'colllocale', pg_catalog.to_jsonb(c)->>'colliculocale'),
       c.collcollate, c.collctype, pg_catalog.to_jsonb(c)->>'collisdeterministic', c.collversion
FROM pg_catalog.pg_collation c JOIN pg_catalog.pg_namespace n ON n.oid = c.collnamespace
WHERE n.nspname = %s AND c.collname = %s AND {_PG_COLLATION_ACCESS}
ORDER BY c.collencoding DESC LIMIT 1
"""
_TYPE = f"""
SELECT pg_catalog.format_type(t.typbasetype, t.typtypmod), t.typnotnull,
       pg_catalog.pg_get_expr(t.typdefaultbin, 0),
       ARRAY(SELECT 'CONSTRAINT ' || pg_catalog.quote_ident(k.conname) || ' ' || pg_catalog.pg_get_constraintdef(k.oid)
             FROM pg_catalog.pg_constraint k WHERE k.contypid = t.oid ORDER BY k.conname),
       ARRAY(SELECT pg_catalog.quote_ident(a.attname) || ' ' || pg_catalog.format_type(a.atttypid, a.atttypmod)
             FROM pg_catalog.pg_attribute a WHERE a.attrelid = c.oid AND a.attnum > 0 AND NOT a.attisdropped
             ORDER BY a.attnum)
FROM pg_catalog.pg_type t JOIN pg_catalog.pg_namespace n ON n.oid = t.typnamespace
LEFT JOIN pg_catalog.pg_class c ON c.oid = t.typrelid
WHERE n.nspname = %s AND t.typname = %s AND t.typtype = %s AND {_PG_TYPE_ACCESS}
"""
_QUERIES = {"index": _INDEX, "routine": _ROUTINE, "sequence": _SEQUENCE, "extension": _EXTENSION,
            "collation": _COLLATION, "domain": _TYPE, "composite": _TYPE}
_RELKINDS = {name: code for code, name in _PG_RELATION_KINDS.items()}


def postgres_definition(source: DataSource, kind: str, name: str, *, oid: int | None = None) -> str:
    """Read the exact selected object through catalog deparsers, not by running its SQL."""
    parts = relation_parts(name)
    if not parts or len(parts) != (1 if kind == "extension" else 2):
        raise EngineError("Invalid PostgreSQL catalog name")
    query, params = _QUERIES.get(kind), parts
    if kind in _RELKINDS:
        query = _VIEW if kind in {"view", "materialized view"} else _TABLE
        params = (*parts, _RELKINDS[kind])
    elif kind == "routine":
        if oid is None:
            raise EngineError("Refresh PostgreSQL metadata before opening the routine definition")
        params = (*parts, oid)
    elif kind in {"domain", "composite"}:
        params = (*parts, "d" if kind == "domain" else "c")
    if query is None:
        raise EngineError("Unsupported PostgreSQL catalog object")
    with source._lock:
        if source.kind != "postgres-live" or source.con is None or source.con.closed:
            raise EngineError("Reconnect to PostgreSQL before opening a definition")
        try:
            # Savepoints keep a failed lookup from aborting a user's transaction.
            with source.con.transaction(), source.con.cursor() as cursor:
                cursor.execute(query, params)
                row = cursor.fetchone()
        except Exception as exc:
            raise _safe_error(exc, "PostgreSQL definition lookup") from None
    if row is None:
        raise EngineError("PostgreSQL object is no longer visible; refresh schema")
    return _format_definition(kind, row)


def _format_definition(kind: str, row: tuple) -> str:
    if kind in {"routine", "index", "view", "materialized view"}:
        return row[0].rstrip()
    if kind in _RELKINDS:
        key, bound, columns, constraints = row
        lines = ["-- Column and constraint definitions (not a complete CREATE statement)", *columns, *constraints]
        if key:
            lines.append("PARTITION BY " + key)
        if bound:
            lines.append(bound)
    elif kind == "sequence":
        dtype, start, increment, minimum, maximum, cache, cycle = row
        lines = ["-- Sequence options (not current values or ownership)", f"AS {dtype}", f"START WITH {start}",
                 f"INCREMENT BY {increment}", f"MINVALUE {minimum}", f"MAXVALUE {maximum}", f"CACHE {cache}",
                 "CYCLE" if cycle else "NO CYCLE"]
    elif kind == "extension":
        version, schema, relocatable = row
        lines = [f"Installed version: {version}", f"Schema: {quote_identifier(schema)}",
                 "Relocatable: " + ("yes" if relocatable else "no")]
    elif kind == "collation":
        provider, locale, collate, ctype, deterministic, version = row
        lines = [f"Provider: {_PG_COLLATION_PROVIDERS.get(provider, provider)}"]
        lines.extend(f"{label}: {value}" for label, value in (
            ("Locale", locale), ("LC_COLLATE", collate), ("LC_CTYPE", ctype),
            ("Deterministic", deterministic), ("Version", version),
        ) if value is not None)
    else:
        base, not_null, default, constraints, columns = row
        if kind == "composite":
            lines = ["-- Composite attributes", *columns]
        else:
            lines = ["AS " + base]
            if default is not None:
                lines.append("DEFAULT " + default)
            if not_null:
                lines.append("NOT NULL")
            lines.extend(constraints)
    return "\n".join(lines)
